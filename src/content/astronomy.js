/**
 * 天象（Astronomy）—— **真实数据**驱动的夜空。
 *
 * ## 要治的病：夜空是随机数
 *
 * `src/world/WorldEffects.js` 的星场是这么来的：
 *
 *     for (let i = 0; i < 800; i++) {
 *       pos[i * 3] = (Math.random() - 0.5) * 600;   // ← 随机
 *       ...
 *     }
 *
 * 800 个均匀撒在盒子里的白点，**没有一颗是真星**，也**永远不转**。
 * 玩家抬头看到的"星空"既不是真实天球的样子，也不对应任何一个时刻 ——
 * 这正是"演示数据堆砌"的一族：画面上有个东西占着位置，但那个位置没有信息。
 *
 * ## 这一片换成什么
 *
 * | 旧（随机） | 新（真实） |
 * |-----------|-----------|
 * | 800 个白点，均匀撒在盒子里 | **50 颗真实亮星**（J2000 赤经赤纬 / 星等 / 光谱色） |
 * | 星场永远不动 | 绕**天极**转（一个恒星日一圈），随世界时刻走 |
 * | 没有月亮 | **真实月相**（照亮比 = (1 − cos 2π·相位)/2，锚在真实新月时刻上） |
 * | 没有季节 | **真实二十四节气**与太阳赤纬（最大 ±23.44°，地轴倾角） |
 *
 * ## 数据从哪来（真实出处，2026-11-23 核对）
 *
 * - **亮星表**：J2000 赤经赤纬 / 视星等 / 光谱型 —— 三个独立来源互校：
 *   South Florida Deep Space Observers 的《The 200 Brightest Stars》、
 *   Western Washington University 的 astro101《The Brightest Stars》、
 *   Michigan State 的 AST101 讲义。三份表的 RA/Dec/星等在 ±0.1° / ±0.05 等以内一致。
 * - **朔望月长度**：`29.530588853` 天（29 天 12 时 44 分 3 秒）—— 三个来源一致。
 * - **2026 年真实朔（新月）时刻**：美国海军天文台 / Griffith 天文台口径，
 *   经 moonagetoday.org 与 spaceandtelescope.com 两处独立核对一致（UTC）。
 * - **2026 年真实望（满月）时刻**：同上（UTC）。
 * - **二十四节气**：通用天文历的近似日期（每年浮动 ±1 天）。
 *
 * ## 三条纪律
 *
 * 1. **不读墙钟**：月相的输入是**世界日**（游戏里的第几天），不是 `Date.now()` ——
 *    B118 那道门禁（墙钟不进玩法）仍然成立。世界的第 0 天锚在 **2026-01-01（UTC）**。
 * 2. **判据住生产代码**：`月相()` / `太阳赤纬()` / `节气()` 是这里的纯函数，
 *    门禁只喂坏数据、只核对真实数据的性质（真实朔日相位必须为 0、真实望日相位必须为 0.5）。
 * 3. **缺省不许是"差不多"**：查不到的星、越界的赤纬、坏掉的时刻一律**当场抛**，
 *    不静默兜一个近似值 —— 近似值会让"真实"这件事悄悄变成假的。
 */

