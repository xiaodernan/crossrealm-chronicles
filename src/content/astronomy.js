/**
 * 公历日期 → **距纪元的天数**（可含小数；一天 = 24 小时）。
 *
 * @param {number} 年
 * @param {number} 月 1–12
 * @param {number} 日 1–31（可含小数）
 * @returns {number} 天数（可为负）
 */
export function 距纪元天(年, 月, 日) {
  if (!Number.isFinite(年) || !Number.isFinite(月) || !Number.isFinite(日)) {
    throw new Error(`日期不合法：${年}-${月}-${日}`);
  }
  if (!Number.isInteger(月) || 月 < 1 || 月 > 12) {
    throw new Error(`月份不合法：${月}`);
  }
  const 当年 = 积月[月 - 1] + (是闰年(年) && 月 > 2 ? 1 : 0);
  return 年首天(年) + 当年 + (日 - 纪元.日);
}

/** 是不是闰年（公历规则） */
function 是闰年(y) {
  return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0;
}

/** 从 1 月 1 日到该月 1 日的天数（平年；末位 365 是"到下一年元旦"） */
const 积月 = Object.freeze([0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334, 365]);

/** 该年之前（含该年 1 月 1 日之前）累计的天数 —— 用于纪元对齐 */
function 年首天(y) {
  const 前 = (k) => Math.floor((k - 1) / 4) - Math.floor((k - 1) / 100) + Math.floor((k - 1) / 400);
  return 365 * (y - 纪元.年) + 前(y) - 前(纪元.年);
}

/** 距纪元天 → 公历 { 年, 月, 日 }（日可含小数） */
export function 反推日期(天) {
  if (!Number.isFinite(天)) throw new Error(`世界日不合法：${天}`);
  let 年 = 纪元.年;
  let 余 = 天;
  for (;;) {
    const 长 = 是闰年(年) ? 366 : 365;
    if (余 < 长) break;
    余 -= 长;
    年 += 1;
  }
  let 月 = 1;
  for (let m = 1; m <= 12; m++) {
    const 长 = 积月[m] - 积月[m - 1] + (是闰年(年) && m === 2 ? 1 : 0);
    if (余 < 长) { 月 = m; break; }
    余 -= 长;
  }
  return { 年, 月, 日: 余 + 1 };
}

/**
 * **相位锚点表**：真实朔（相位 0）与真实望（相位 0.5）交替排开，
 * 相位**解缠**（不取模）—— 从 0.5 起每过一个锚点加 0.5，于是相邻锚点之间相位连续。
 *
 * 为什么要两个锚点而不是只用朔：月球的轨道是**椭圆**的 ⇒ 从朔到望的真实间隔
 * 在 14.1–14.8 天之间浮动（平均 14.765 天）。只用朔、拿平均朔望月推算，
 * 到了真实望日相位会偏 **0.02–0.027**（照亮比差 2 个百分点）——
 * 那是"差不多像真实"，不是真实。**两端都锚在真实时刻上**，中间才是插值。
 */
function 锚点表() {
  const 表 = [];
  for (const s of 真实朔) 表.push({ 天: 距纪元天(纪元.年, s.月, s.日 + s.时 / 24), 相: 0 });
  for (const f of 真实望) 表.push({ 天: 距纪元天(纪元.年, f.月, f.日 + f.时 / 24), 相: 0.5 });
  表.sort((a, b) => a.天 - b.天);
  表.forEach((锚, i) => { 锚.解缠 = 0.5 * (i + 1); });
  return 表;
}

let 锚点缓存 = null;

/**
 * **月相**（真实）。
 *
 * - `相位`：0 = 朔，0.25 = 上弦，0.5 = 望，0.75 = 下弦（0…1 的循环量）；
 * - `照亮比`：0…1 —— **真实定义** `(1 − cos 2π·相位) / 2`；
 * - `距朔`：离上一个朔多少天。
 *
 * @param {number} 世界天 距纪元的天数（可含小数）
 */
export function 月相(世界天) {
  if (!Number.isFinite(世界天)) throw new Error(`世界日不合法：${世界天}`);
  if (!锚点缓存) 锚点缓存 = 锚点表();
  const 表 = 锚点缓存;
  let 解缠;
  if (世界天 <= 表[0].天) {
    // 早于表头：按平均朔望月往前推
    解缠 = 0.5 - (表[0].天 - 世界天) / 朔望月;
  } else if (世界天 >= 表[表.length - 1].天) {
    const 末 = 表[表.length - 1];
    解缠 = 末.解缠 + (世界天 - 末.天) / 朔望月;
  } else {
    let i = 0;
    while (i + 1 < 表.length && 表[i + 1].天 <= 世界天) i += 1;
    const 左 = 表[i];
    const 右 = 表[i + 1];
    const 比 = (世界天 - 左.天) / (右.天 - 左.天);
    解缠 = 左.解缠 + 比 * (右.解缠 - 左.解缠);
  }
  const 相位 = ((解缠 % 1) + 1) % 1;
  const 照亮比 = (1 - Math.cos(2 * Math.PI * 相位)) / 2;
  const 序 = Math.round(相位 * 8) % 8;
  return {
    相位,
    照亮比,
    距朔: ((解缠 % 1) + 1) % 1 * 朔望月,
    序,
    名: 相名[序],
  };
}

/**
 * **太阳的平黄经**（度）—— 太阳在黄道面上的位置。
 *
 * 春分（黄经 = 0）钉在**节气表那一格**（3 月 20 日）—— 同一件事不许两处各说一套。
 * 之后按**回归年**（365.2422 天）匀速前进。
 *
 * **口径如实记下**：真实地球轨道是椭圆 ⇒ 四季长短不等（春分→夏至 93 天、
 * 夏至→秋分 93 天、秋分→冬至 90 天、冬至→春分 89 天）。一个匀速的平黄经
 * 复刻不了这件事，于是本式把**秋分推到 9 月 19 日前后**（节气表是 9 月 22/23 日，
 * 差 3 天），夏至与冬至则落在 6 月 20 日与 12 月 19 日前后（各差 1~2 天）。
 * 差的是**几天的季节漂移**，不是"有没有季节"—— 太阳赤纬照样在 ±23.44° 之间摆。
 *
 * @param {number} 世界天
 */
export function 太阳黄经(世界天) {
  if (!Number.isFinite(世界天)) throw new Error(`世界日不合法：${世界天}`);
  const 日期 = 反推日期(世界天);
  const 距春分 = 世界天 - 距纪元天(日期.年, 3, 20);
  return (((距春分 * 360) / 年长) % 360 + 360) % 360;
}

/**
 * **黄经 → 赤道坐标**（黄道面与赤道面的交角 = 地轴倾角）。
 *
 * 月亮绕黄道走、太阳也在黄道上走 —— 只有把两者都换算到赤道坐标，
 * 它们之间的**角距**才是真的（黄经差 = 月相 × 360°）。
 *
 * @param {number} 黄经度 黄经（度，0 = 春分点）
 * @returns {{赤经时: number, 赤纬: number}} 赤经（小时）/ 赤纬（度）
 */
export function 黄道赤道(黄经度) {
  if (!Number.isFinite(黄经度)) throw new Error(`黄经不合法：${黄经度}`);
  const λ = (黄经度 * Math.PI) / 180;
  const ε = (地轴倾角 * Math.PI) / 180;
  const 赤经 = Math.atan2(Math.sin(λ) * Math.cos(ε), Math.cos(λ));
  const 赤纬 = Math.asin(Math.sin(ε) * Math.sin(λ));
  return {
    赤经时: (((赤经 * 180) / Math.PI + 360) % 360) / 15,
    赤纬: (赤纬 * 180) / Math.PI,
  };
}

/**
 * **太阳的赤道坐标** —— 季节决定它有多高。
 *
 * @param {number} 世界天
 */
export function 太阳赤道坐标(世界天) {
  return 黄道赤道(太阳黄经(世界天));
}

/**
 * **月亮的赤道坐标** —— 真实月相的几何。
 *
 * 月亮的**黄经差** = 月相 × 360°（朔 = 0°、上弦 = 90°、望 = 180°），
 * 这是真实月相的**定义**，不是近似：差一个黄经差就等于差一次月相。
 * 黄纬（±5.1°）不计 —— 它只影响月亮在黄道上下偏多少，不影响角距。
 *
 * @param {number} 世界天
 */
export function 月亮赤道坐标(世界天) {
  const 相 = 月相(世界天);
  return 黄道赤道(太阳黄经(世界天) + 相.相位 * 360);
}

/**
 * **太阳赤纬**（度）—— 黄道上的太阳投到赤道面后的高度。
 *
 * `δ = asin(sin ε · sin λ)`，ε = 地轴倾角、λ = 平黄经。
 * 振幅就是地轴倾角：夏至 ≈ +23.44°、冬至 ≈ −23.44°。
 *
 * @param {number} 世界天
 */
export function 太阳赤纬(世界天) {
  return 太阳赤道坐标(世界天).赤纬;
}

/**
 * **当前节气**（真实表）。
 *
 * @param {number} 世界天
 * @returns {{名: {zh: string, en: string}, 季: string, 序: number, 距下一个: number}}
 */
export function 节气(世界天) {
  if (!Number.isFinite(世界天)) throw new Error(`世界日不合法：${世界天}`);
  const 候选 = 节气表
    .map((j, 序) => ({ j, 序, 天: 距纪元天(纪元.年, j.月, j.日) }))
    .filter((x) => x.天 <= 世界天)
    .sort((a, b) => a.天 - b.天);
  const 命中 = 候选[候选.length - 1];
  if (!命中) {
    // 早于表头：用第一个节气的名目，跨年的那一个
    const 首 = 节气表[节气表.length - 1];
    return { 名: 首.名, 季: 首.季, 序: 23, 距下一个: 距纪元天(纪元.年, 首.月, 首.日) - 世界天 };
  }
  const 下一个 = 节气表[(命中.序 + 1) % 节气表.length];
  // 节气表按**节气年**排（立春 → 大寒），而大寒/小寒落在公历一月 ——
  // 所以"下一个"可能落在**下一年**（跨年那一格）。
  let 下一个天 = 距纪元天(纪元.年, 下一个.月, 下一个.日);
  if (下一个天 <= 世界天) 下一个天 += 是闰年(纪元.年 + 1) ? 366 : 365;
  return {
    名: 命中.j.名,
    季: 命中.j.季,
    序: 命中.序,
    距下一个: 下一个天 - 世界天,
  };
}

/**
 * 天球坐标 → 单位方向向量（赤道坐标系）。
 *
 * @param {number} 赤经时 赤经（小时，0–24）
 * @param {number} 赤纬度 赤纬（度）
 * @returns {{x: number, y: number, z: number}}
 */
export function 天球向量(赤经时, 赤纬度) {
  if (!Number.isFinite(赤经时) || !Number.isFinite(赤纬度)) {
    throw new Error(`天球坐标不合法：${赤经时} / ${赤纬度}`);
  }
  if (赤经时 < 0 || 赤经时 >= 24) throw new Error(`赤经越界：${赤经时}（0–24 小时）`);
  if (赤纬度 < -90 || 赤纬度 > 90) throw new Error(`赤纬越界：${赤纬度}（−90…90 度）`);
  const 时角 = (赤经时 / 24) * 2 * Math.PI;
  const 赤纬弧 = (赤纬度 * Math.PI) / 180;
  const 余纬 = Math.cos(赤纬弧);
  return {
    x: 余纬 * Math.cos(时角),
    y: Math.sin(赤纬弧),
    z: 余纬 * Math.sin(时角),
  };
}

/**
 * 星等 → 屏幕上的**大小**与**亮度**（点光的观感映射）。
 *
 * 真实关系是 `亮度比 = 2.512 ^ Δ星等`；这里取其立方根附近的一条温和曲线，
 * 让最亮的一批星明显大于其余（肉眼在夜空里看到的正是这样：亮星压过暗星）。
 *
 * @param {number} 星等
 * @returns {{大小: number, 亮度: number}}
 */
export function 星等映射(星等) {
  if (!Number.isFinite(星等)) throw new Error(`星等不合法：${星等}`);
  // 大小：指数曲线，**基准点取 4.6 等 = 1 像素**。
  // 早先取 1.6 等 = 1.15 px，于是 3 等以下全是亚像素（3.31 等的天权星只有 0.805 px）：
  // 亚像素的点精灵在不同驱动上有的被舍成 0（那颗星就凭空消失）、
  // 有的被补成 1 px（于是它比真正的邻星还亮）。把基准点挪到 4.6 等，
  // 全表（最暗 3.31 等 → 1.32 px）都落在 1 px 以上，而曲线仍**处处严格单调**。
  const 大小 = Math.pow(2, (4.6 - 星等) / 3.2);
  // 亮度：亮端线性、暗端指数 —— 两段在 3 等处接得上，且**处处严格单调**
  // （早先暗端被硬钳在 0.16 ⇒ 3 等与 4 等一样亮 ⇒ 暗星之间分不出层次）。
  const 亮度 = 星等 <= 3
    ? 0.08 + 0.92 * ((3 - 星等) / 4.5)
    : 0.08 * Math.pow(2, (3 - 星等) / 2);
  return { 大小: Math.min(4.2, Math.max(1, 大小)), 亮度: Math.min(1, 亮度) };
}
