/**
 * 舱壁与熔断 —— Spring Cloud（Hystrix / Resilience4j）语义的**内化**。
 *
 * ## 要治的病：主循环里任何一个子系统抛异常，整局就死了
 *
 * `core/Game.js` 的 `run()` 在**这个切片之前**是这一行：
 *
 *     const loop = () => { requestAnimationFrame(loop); this.update(); this.render(); };
 *
 * 而 `update()` 里有 **58 处**子系统调用（`this.combatStyle?.update(dt)` /
 * `this.world.update(...)` / `this.hud.update(dt)` / …），**一处都没有 try/catch**。于是
 * 任何一个子系统抛异常的后果是：
 *
 * - `this.update()` 抛出 ⇒ `this.render()` **这一帧不执行** ⇒ 画面停在上一帧；
 * - `requestAnimationFrame(loop)` 已经排上了 ⇒ 下一帧照样抛、照样不渲染 ⇒
 *   **画面永久冻结**，控制台每秒刷一条未捕获异常，而堆栈指向的是"谁抛的"这件事本身。
 *
 * 玩家看到的是"卡死了"，开发者看到的是"不知道是谁炸的"。这不是理论上的可能性 ——
 * 仓里已经有第二处同族的病（B161：门禁读源码时跨行锚点在 CRLF 检出上静默 no-op，
 * 判据读着好源码却什么都没量）。**机制能坏到没人看得见**，本仓已经吃过一次。
 *
 * ## 借 Spring Cloud 的哪几个契约，为什么不引 Java
 *
 * 这里的"Spring Cloud"指的是**四个契约**，不是一套部署拓扑：
 *
 * | 契约 | 在这里的落法 |
 * |------|--------------|
 * | **舱壁隔离（bulkhead）** | 每个子系统一个舱壁；一个炸了只停它自己，其余照跑 |
 * | **熔断降级（circuit breaker + fallback）** | 连续失败达阈值 ⇒ 断开 ⇒ 后续帧短路并交降级值；冷却到 ⇒ 半开探测 ⇒ 好了就闭合，没好就再断开 |
 * | **服务注册与发现（registry / discovery）** | 舱壁组本身就是注册表：一个子系统**被跑过一次**就在名册里，且名册**双向**——跑过的都登记、登记的都跑过 |
 * | **健康判据（health）** | `舱壁账()` 是唯一读数口；健康 = 全部闭合且零未清错误 |
 *
 * **不引 Java 栈**：仓库范围是"Three.js 网页版"（README 明写），引 JVM 构建链会让 CI 从
 * 六步膨胀成另一套，而浏览器端也消费不到 Eureka 的心跳 —— 那是把一个进程拓扑搬进一个
 * 纯前端仓库，换不来任何玩家能感知的东西。这里做的是**语义内化 + 协议面对齐**：
 * 数据形状照 Spring Cloud Config / Actuator 的习惯来，将来真接一台 Spring Cloud
 * 服务端，前端这一层不改。
 *
 * ## 三条纪律
 *
 * 1. **计时只走主循环的 dt**（README 硬性约束）：冷却计时吃调用方传进来的 `dt`，
 *    本模块**不**开 `setTimeout`、**不**自建 rAF。传进来的那个 `dt` 必须是**基建时钟**
 *    （`Game` 里的 `rawDt` —— 真实帧间隔），不是玩法的 `dt`（那个会被慢动作与命中停顿
 *    拉到 0，熔断冷却就永远走不完）。
 * 2. **判据住生产代码**：`舱壁账()` 与状态机都在这里，诊断与门禁读同一处（与碰撞体
 *    `owner`、配置 `DRAW_CALL_BUDGETS` 同一套路）。
 * 3. **熔断期间不许再抛**：下游一旦断开，调用方拿到的是**降级值 + 一份失败账**，不是异常
 *    —— 异常再抛出去就等于没熔断，那只是把 try/catch 换了个地方写。
 */

/** 熔断三态（与 Spring Cloud Actuator 的 `CircuitBreaker.State` 同名同义） */
export const 闭合 = 'closed';
export const 打开 = 'open';
export const 半开 = 'half-open';

/** 默认连续失败阈值：连续 3 次失败就断开这一条子系统 */
export const 默认失败阈值 = 3;
/** 默认冷却秒：断开后多久放一次探测 */
export const 默认冷却秒 = 2;

/**
 * 建一个舱壁。
 *
 * @param {string} 名 子系统名（注册表与降级提示都用它）
 * @param {object} 选
 * @param {number} 选.失败阈值 连续失败多少次就断开（≥1）
 * @param {number} 选.冷却秒 断开后多久放一次探测（≥0）
 * @param {Function} 选.降级 断开期间交什么值出去（不声明 ⇒ `undefined`）
 */
export function 建舱壁(名, { 失败阈值 = 默认失败阈值, 冷却秒 = 默认冷却秒, 降级 } = {}) {
  if (typeof 名 !== 'string' || 名.length === 0) {
    throw new Error(`舱壁要一个非空的名字，收到 ${JSON.stringify(名)}`);
  }
  if (!Number.isFinite(失败阈值) || 失败阈值 < 1) {
    throw new Error(`舱壁「${名}」的失败阈值要在 1 以上，收到 ${失败阈值}`);
  }
  if (!Number.isFinite(冷却秒) || 冷却秒 < 0) {
    throw new Error(`舱壁「${名}」的冷却秒不能是负数，收到 ${冷却秒}`);
  }
  return {
    名,
    失败阈值,
    冷却秒,
    降级,
    /** 三态：闭合 / 打开 / 半开 */
    态: 闭合,
    /** 连续失败次数（成功一次就清零） */
    连续失败: 0,
    /** 打开态里还剩多少秒才放探测 */
    剩余冷却: 0,
    /** 累计真的调用过下游的次数 */
    调用数: 0,
    /** 累计失败次数（不清零，是账） */
    失败数: 0,
    /** 累计短路次数（熔断期间没调下游） */
    短路数: 0,
    /** 累计熔断次数（断开过几次） */
    熔断次数: 0,
    /** 最近一次错误（诊断用） */
    最近错误: null,
  };
}

/**
 * 走一次舱壁。
 *
 * 状态机：
 * - **闭合**：正常跑。成功 ⇒ 连续失败清零；失败 ⇒ 连续失败 +1，达阈值就断开。
 * - **打开**：**不调下游**（这正是熔断的意义），冷却没走完就短路返回降级值；
 *   冷却走完 ⇒ 转**半开**，放一次探测。
 * - **半开**：只放一次探测。成功 ⇒ 回闭合（连续失败清零）；失败 ⇒ 重新打开，冷却重计。
 *
 * @param {object} 舱壁 `建舱壁()` 的产物
 * @param {Function} fn 要跑的下游
 * @param {number} dt **基建时钟**的帧间隔（秒）
 * @param {object} [追踪] 链路追踪器（`platform/tracing.js`）。给了就记 span：
 *   调用发生 ⇒ 一个 span（耗时、成没成）；熔断短路 ⇒ 一个 0 毫秒的"跳过"span。
 *   **不记也不影响本函数的行为** —— 追踪是仪器，不是判据。
 * @returns {{成: boolean, 值: any, 错误: Error|null, 短路: boolean, 熔断: boolean}}
 */
export function 舱壁调用(舱壁, fn, dt = 0, 追踪 = null) {
  if (舱壁.态 === 打开) {
    舱壁.剩余冷却 -= Number.isFinite(dt) ? dt : 0;
    if (舱壁.剩余冷却 > 0) {
      舱壁.短路数 += 1;
      追踪?.记(舱壁.名, 0, false, true);
      return { 成: false, 值: 舱壁.降级, 错误: null, 短路: true, 熔断: false };
    }
    // 冷却走完 —— 放一次探测
    舱壁.态 = 半开;
  }

  舱壁.调用数 += 1;
  try {
    const 值 = 追踪 ? 追踪.包(舱壁.名, fn) : fn();
    舱壁.连续失败 = 0;
    if (舱壁.态 === 半开) 舱壁.态 = 闭合;
    return { 成: true, 值, 错误: null, 短路: false, 熔断: false };
  } catch (错误) {
    舱壁.失败数 += 1;
    舱壁.连续失败 += 1;
    舱壁.最近错误 = 错误;
    // 半开里失败 = 探测失败，立刻再断；闭合里要攒够阈值才断
    const 该断 = 舱壁.态 === 半开 || 舱壁.连续失败 >= 舱壁.失败阈值;
    if (该断) {
      舱壁.态 = 打开;
      舱壁.剩余冷却 = 舱壁.冷却秒;
      舱壁.熔断次数 += 1;
    }
    return { 成: false, 值: 舱壁.降级, 错误, 短路: false, 熔断: 该断 };
  }
}

/**
 * 舱壁读数 —— **唯一**的读数口。诊断与门禁都读这里。
 */
export function 舱壁账(舱壁) {
  return {
    名: 舱壁.名,
    态: 舱壁.态,
    连续失败: 舱壁.连续失败,
    失败阈值: 舱壁.失败阈值,
    调用数: 舱壁.调用数,
    失败数: 舱壁.失败数,
    短路数: 舱壁.短路数,
    熔断次数: 舱壁.熔断次数,
    最近错误: 舱壁.最近错误
      ? String(舱壁.最近错误?.message ?? 舱壁.最近错误)
      : null,
  };
}

/**
 * 舱壁组 —— 一份**注册表**（Spring Cloud 的服务注册与发现语义）。
 *
 * 一个子系统**被跑过一次**就在名册里；名册双向可查：跑过的都登记、登记的都跑过。
 * 组的另一头是"健康"：全部闭合且零未清错误 ⇒ 健康。
 *
 * @param {object} 选
 * @param {number} 选.失败阈值
 * @param {number} 选.冷却秒
 * @param {any} 选.降级
 * @param {object} [选.追踪] 链路追踪器（`platform/tracing.js`）。给了就把每次调用记成 span。
 */
export function 建舱壁组({ 失败阈值 = 默认失败阈值, 冷却秒 = 默认冷却秒, 降级 = undefined, 追踪 = null } = {}) {
  const 册 = new Map();

  /** 取（或现建）一条舱壁。降级值只在这一条**第一次**建的时候登记 —— 名字重复不许改账。 */
  const 取 = (名, 降级) => {
    let 舱壁 = 册.get(名);
    if (!舱壁) {
      舱壁 = 建舱壁(名, { 失败阈值, 冷却秒, 降级 });
      册.set(名, 舱壁);
    }
    return 舱壁;
  };

  return {
    取,
    /**
     * 跑一个子系统。返回 `舱壁调用()` 的完整结果，调用方通常只要 `.值`。
     * @param {string} 名
     * @param {Function} fn
     * @param {number} dt 基建时钟的帧间隔
     */
    跑(名, fn, dt = 0) {
      return 舱壁调用(取(名), fn, dt, 追踪);
    },
    /** 名册（注册表读数） */
    名册() {
      return [...册.values()].map(舱壁账);
    },
    /** 不在闭合态的舱壁（真坏的） */
    坏舱壁() {
      return [...册.values()].filter((c) => c.态 !== 闭合).map((c) => c.名);
    },
    /** 健康判据：全部闭合，且没有留着一个未清的最近错误 */
    健康() {
      return [...册.values()].every((c) => c.态 === 闭合 && c.最近错误 === null);
    },
    /** 清空注册表（换关 / 重开局时用） */
    清空() {
      册.clear();
    },
  };
}
