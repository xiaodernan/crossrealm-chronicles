/**
 * 地下城的尺寸事实各说一次（W-B10 切片4f）。
 *
 * ## 为什么要有这一份
 * 动手之前「一格 18 米」在役源码里有 **9 处**写法（`MazeLayout` 与 `RoomTemplates` 各自的模块级
 * `const CELL = 18`、`LevelEditor` 里三份局部 `const CELL = 18` + 两处裸 `18` 的除法 + 两份布局默认值），
 * 「一扇门 4 米」有 **4 处**，而门板 / 门框 / 门离地高度各抄了一份"看起来像常量"的字面量
 * （普查 `.tmp-20261004/wb10s4f-census.mjs`，合计 27 处）。抄本的症状不是今天算错 —— 它们今天
 * 恰好同值 —— 而是**改一个数要改九处，漏一处的症状是静默脱节**。实测两条：
 * - 编辑器：喂它一份 `cellSize: 25` 的导入布局，放置房间仍按 18 落位（`(gx,gz)=(2,1)` 得到
 *   `x=36` 而不是 `50`），拖动后按 `Math.round(60/18)` 反推格号，把 `r_2_1` 改名成 `r_3_2` ——
 *   同一间房在两套格子里各有一个名字（普查 ④）。
 * - 门：`537` 扇门的洞逐扇量出来都是 4 米，而门板沿墙只有 3.5 米 ⇒ **每侧见光 0.25 米**，
 *   关着的门盖不住自己的门洞（普查 ③）。门板宽本来是门洞宽的一个派生量，抄成常量之后就漂了。
 *
 * ## 两条口径
 * - **声明在这里，运行时载体在 `layout` 上**。`MazeLayout` 把 `cellSize / bossCell / wallH /
 *   wallT / doorWidth / bossDoorWidth` 写到每张布局对象上；几何层与编辑器读**布局**而不是读常数。
 *   这一条是编辑器那处脱节的根：一份导入的布局只有按自己的 `cellSize` 走，"编辑这一份布局"才成立。
 * - **派生量就地算，不再新写数字**：门板沿墙 = 门洞宽 − 每侧让缝，门框沿墙 = 门洞宽 + 收边，
 *   门碰撞跨洞半轴 = 门洞宽 / 2，门板离地 = 板高 / 2，门框离地 = 框高 / 2。后两条不是猜的 ——
 *   源码里原本写的 `2.1` 与 `2.4` 恰好就是 `4.2/2` 与 `4.8/2`。
 *
 * ## 这一片**没有**动的两件事（已登记，见台账）
 * - Boss 场自己的墙开 5 米的洞，但 `makeDoor` 在 `isBossArena` 被标记**之前**就跑完了，
 *   所以 9 扇由 Boss 场造出的门仍站在邻居的边界线上（±9 而不是 ±17），Boss 场那四面墙上
 *   一个门板都没有 —— 那是 B79 的形状问题，不在"抄本收口"这一片里改位置。
 * - 门碰撞盒的**轴向**不分南北/东西（长轴恒在 x）：246 扇东西向门的跨洞半轴只有 0.45 米，
 *   比洞半宽 2.00 米差 1.55 米，靠的是墙段自己的碰撞盒补住。改轴向会动到碰撞，另片处理。
 */

/** 一格 / 一间普通房的边长（米） */
export const CELL = 18;
/** Boss 场的边长。注意它只占**一个格位**，所以它与邻居重叠 `BOSS_CELL/2 − CELL/2 = 8` 米（B79） */
export const BOSS_CELL = 34;
/** 墙高 */
export const WALL_H = 5;
/** 墙厚 */
export const WALL_T = 0.6;
/** 普通房的门洞宽（沿墙方向那个洞的跨度） */
export const DOOR_WIDTH = 4;
/** Boss 场自己墙上的门洞宽 —— 今天没有门板落在这条线上（见文件头），但 `_buildBossArena` 确实在开这个洞 */
export const BOSS_DOOR_WIDTH = 5;

/** 门板沿墙方向**每侧**让出的缝：让门板不跟墙段端面共面（共面就会有 z-fighting 的一条亮边） */
export const DOOR_JAMB = 0.05;
/** 门板高 / 厚 */
export const DOOR_H = 4.2;
export const DOOR_T = 0.5;
/** 门框沿墙方向比门洞多出的总收边（两侧合起来） */
export const DOOR_FRAME_OVER = 0.2;
/** 门框高 / 厚 */
export const DOOR_FRAME_H = 4.8;
export const DOOR_FRAME_T = 0.15;
/** 门碰撞盒沿**通道方向**的半轴（跨洞那一轴是门洞宽 / 2，就地派生） */
export const DOOR_COLLIDER_HALF_DEPTH = 0.45;

/**
 * 敌人出生点的散布跨度：`(rnd() − 0.5) * (CELL − SPAWN_SPAN_MARGIN)` ⇒ 距房心 ±(CELL−6)/2 = ±6 米，
 * 也就是每面墙前留 3 米。写成一个数是因为它跟着一格边长走，不该再抄一次 18。
 */
export const SPAWN_SPAN_MARGIN = 6;
