/**
 * 无头 harness 的读数完整性判定（W-C2 切片6b，#165）—— `npm run perf`、`npm run e2e`
 * 与 `npm run e2e:combat` 共用的"这一轮的数到底是不是数"。
 *
 * ## 为什么单独一个文件（以及为什么它不叫 perf-*）
 *
 * `perf-smoke.mjs`、`e2e-clear.mjs`、`e2e-combat.mjs` 三个都是**导入即执行**的（顶层就起 vite 与 Chrome），门禁不能
 * import 它们 —— 那是 W-D4 切片3 立下的分家。所以"什么算一个交出来的读数"这条判据住在这里，
 * 两个脚本与门禁问的是**同一个判**（`src/engine/drawCallBudget.js` 之于上限表是同一条纪律）。
 * 切片6c 把 e2e-clear 也接进来之后，名字里的 `perf-` 就成了谎话 —— 它守的是"任何一条用 CDP
 * 驱动无头页的门禁"，两把尺一旦分家，下一次红的就是其中一把。
 * 切片7c 把战斗门禁的那张**越线表**也搬进来，理由比"省一份 import"具体：这一族判据第一次
 * 真跑（r7）红了两条，两条都是判据自己踩空（首末态相等当成卡死、在断气那一帧读魂火账），
 * 而这种东西在脚本里**没法被演示** —— 搬成纯函数之后，"卡住的轨迹必须红"与"走完连段的轨迹
 * 必须绿"两条都能在合成读数上当场跑给门禁看。
 *
 * ## 这一片在补的那半个洞
 *
 * 预算表比的是 `枢纽.updateAvgMs > 预算.updateAvgMs` 这样的**大于**式。NaN 不参与大于：
 * `NaN > 40` 是 false，于是"页面里那 240 帧的账根本没交出来"这一轮会**绿**。
 * 2026-10-21 的阴影普查（`.tmp-wc2s6/`）在同一条腿上真撞上过一次：hub 那一站的 ms 腿抛错，
 * 整站的物件名册差点被一起丢掉 —— 差别只在于那一次是**我写的 try 把它吞了**，
 * 而这把尺子吞的时候连一句红都不报。
 *
 * 所以这里只问一件事：**每一站、每一列都得是有限正数，站点集合得与名单逐格对齐**，
 * 外加四条"这一轮连的是不是我自己起的那个页、那个页中途有没有被换掉"的归属判据。
 * 它不问"好不好的数"（那是预算表的事），也不给任何容差 —— 容差会变成下一次红之后
 * 被放宽的那个数。
 */

/** 有限正数：0 与 NaN 与 Infinity 都不是"量到了" */
export const 是有限正数 = (v) => typeof v === 'number' && Number.isFinite(v) && v > 0;

/** draw call 腿的三列（也是 `perf-smoke` 往页面里那句话要的三个字段） */
export const DRAW列 = Object.freeze(['整帧', '本体', '阴影']);

/**
 * draw 腿的**附列**（W-C2 切片12，B154）：它们**不参与达标**，是"这一读是在什么世界状态下读的"的见证。
 *
 * ## 为什么一把只钉了四个自由度的尺，需要第五个见证
 *
 * `DRAW_CALL_RECIPE` 钉住时刻 / 朝向 / 俯角 / 结算帧数，2026-10-28 又把站点钉上世界种子 ——
 * 切片12 的跨页探针（`.tmp-20261029-s16/spread.mjs`，同种子、每页只读一次、连开四页）证明
 * **布局这一项已经钉住了**（八站里六站逐字同值，hub 与 radiant 各差 2）。可 `整帧 / 本体` 两列
 * 同期仍有 20–40 个 call 的差（hub 283 → 288 → 258），而**数出来的那一列（`阴影趟`）一动不动**。
 * 两刀切下来（`.tmp-20261029-s16/mech2.mjs`，同一个页、来回路过同一站）：
 * - 离开这一站再回来 → **+5**（第 1、2 遍回都是 288，`数出来` 仍 62）；
 * - 第三遍之后 → **−25**，且少的 **21 件全是不投影的**（日志里每一行都写着 `投=否`）——
 *   所以 `数出来` 当然不变，而 `可画件` 同期从 744 掉到 695，两列对得上。
 *
 * 少的东西有形状：八面体本体 + 作为它孩子的地面环与光柱（`LootSystem` 的掉落三件套），
 * 摘出时父件 `parent = null`、孩子仍 `有父` 但已不在场景树里 —— 正是 `scene.remove` + 归还池的那一步。
 * 它们的寿命 `DROP_LIFE = 30` 走的是 `dt`（**真实时间**），不是钉住的 `timeOfDay`。
 * 一句话：**页龄**是这一把尺没钉的第五个自由度，而它动的恰好是 `整帧 / 本体` 那两列。
 *
 * ## 所以这一列要留下来
 *
 * 归因花了三个探针、十几分钟的真页。把"读的时候地上有几件掉落、场景里有多少可画件"打在每一行
 * 读数后面，下一次 25 个 call 的差**一行话就能判**是内容涨了还是页龄耗尽 —— 不必再跑探针。
 * 判据只要它们是**非负整数**：0 在这里是合法值（地上确实可以一件掉落都没有），
 * 与上面三列"0 = 没量到"不同 —— 那三列是尺子，这两列是见证。
 */
export const DRAW附列 = Object.freeze(['掉落', '可画件']);

/**
 * draw 腿的**对照列**（W-C2 切片14，B157）：**掉落在这个机位上占了几个 call**，开 / 关阴影各一份。
 *
 * ## 为什么读数里不能带着它
 *
 * 归因做完之后的结论：切片13 那条“地板过期”腿点名的 5 格里，四格所在的区那一片
 * 什么都没加 —— 差的那几个 call 是**地上剩几件掉落**（一件三年套：八面体本体 + 地面环
 * + 光柱，全部 MeshBasic / MeshStandard，**一件都不投影**）。它们的寿命走真实时间 ⇒ 同一份
 * 内容在不同页上能差 5–25 个 call。那么读数就不该带着它，但也不能就这么把它丢掉 ——
 * 日志里那个数（今天 hub 泡 23 个）是下一次归因的第一手证据。
 *
 * ## 为什么是两列而不是一列
 *
 * 整个切片的前提是“掉落不投影”。那就拿它自己去验：开与关阴影两个冻结对里，
 * 它占的 call 数必须**相等** —— 不等就说明那几件东西跟阴影这一轮搅在一起了，“把它从读数里
 * 拿掉”这个前提不成立，读数作废。
 *
 * ## 为什么要冻结对口径而不是两个一趟()
 *
 * 第一版用“含掉落一趟 / 不含掉落一趟”相减，void 那站当场读出“含 122 < 不含 123”：
 * 两趟之间隔着一次 update()，世界又走了一步（少的是别人，不是掉落）。冻结对中间
 * 一步不推，只翻可见性 ⇒ 差就只能是掉落自己。
 */
export const DRAW对照列 = Object.freeze(['掉落call', '掉落call关']);

/** CPU 腿的三列（每列都得是有限正数，否则预算表的 `>` 会绿在空尺上） */
export const CPU列 = Object.freeze(['updateAvgMs', 'updateP95Ms', 'frameAvgMs']);

/**
 * draw call 腿：一站交出来的东西得长什么样。
 *
 * 三条各自的理由：
 * - **整数**：`renderer.info.render.calls` / `.triangles` 只会给整数。读到非整数（含 NaN）
 *   说明这句话压根没跑到，或跑到的是别的页。
 * - **正数**：0 不是"很好"，是"没量到"。三列里任何一列为 0 都让那一站的分母失去意义。
 * - **差值自洽**：阴影列在页面里就是 `整帧 − 本体`。脚本这边再算一次、比一遍，为的是把
 *   "那一列的算法"钉住 —— 将来有人把它改成第三趟取账，这里会红，而不是让两列悄悄同源。
 */
export function draw读数问题(站id, r) {
  const 问 = [];
  if (!r || typeof r !== 'object') {
    return [`站点 ${站id} 没交出读数对象（拿到 ${JSON.stringify(r)}）`];
  }
  for (const 列 of DRAW列) {
    const v = r[列];
    if (!Number.isInteger(v)) {
      问.push(`站点 ${站id} 的 "${列}" 列不是整数（读到 ${String(v)}）—— info.render.calls 只会给整数，非整数=这一趟没跑到`);
    } else if (!(v > 0)) {
      问.push(列 === '阴影'
        ? `站点 ${站id} 的阴影趟读到 ${v}（整帧 ${r.整帧} / 本体 ${r.本体}）—— 关阴影没有减少任何 call，两列分家就是假的`
        : `站点 ${站id} 的 "${列}" 列读到 ${v} —— 0 不是"达标"，是没量到`);
    }
  }
  if (Number.isInteger(r.整帧) && Number.isInteger(r.本体) && Number.isInteger(r.阴影)
    && r.阴影 !== r.整帧 - r.本体) {
    问.push(`站点 ${站id} 的三列不自洽：阴影 ${r.阴影} ≠ 整帧 ${r.整帧} − 本体 ${r.本体} —— 两列不再是同一帧的差值`);
  }
  if (!Number.isInteger(r.三角面) || !(r.三角面 > 0)) {
    问.push(`站点 ${站id} 的 tri 读到 ${String(r.三角面)} —— 画了 call 却没画面，这一站的取账落在空场景上`);
  }
  /**
   * 对照列（切片14）：先问“量到了吗”（与主列同一条标准），再问“比主列小了吗”。
   */
  for (const 列 of DRAW对照列) {
    const v = r[列];
    if (!Number.isInteger(v) || v < 0) {
      问.push(`站点 ${站id} 的对照列 "${列}" 读到 ${String(v)} —— 掉落在一个机位上占的 call 数只能是非负整数（地上一件没有就是 0）`);
    }
  }
  if (Number.isInteger(r.掉落call) && Number.isInteger(r.掉落call关) && r.掉落call !== r.掉落call关) {
    问.push(`站点 ${站id} 的掉落占比在开/关阴影两个冻结对里不一样（${r.掉落call} 对 ${r.掉落call关}）—— 掉落本来不投影：不一样就说明“把它从读数里拿掉”这个前提不成立`);
  }
  for (const 列 of DRAW附列) {
    const v = r[列];
    if (!Number.isInteger(v) || v < 0) {
      问.push(`站点 ${站id} 的附列 "${列}" 读到 ${String(v)} —— 附列不参与达标，但少了这份见证，`
        + '下一次 20–40 个 call 的差就只能再跑一次几分钟的探针去猜是谁（切片12 就是这么把瞬态掉落找出来的）');
    }
  }
  return 问;
}

/**
 * 阴影普查腿（W-C2 切片10，B151）：**数出来的那一趟**必须等于**同一份世界状态下减出来的那一趟**。
 *
 * ## 这一条补的是哪个洞
 *
 * 阴影列一直是 `整帧 − 本体`，而两趟之间隔着一次 `update()`。减法成立的前提是"这两趟之间
 * 除了阴影趟本身什么都没变"，游戏里不成立：敌人每帧在走，主趟的视锥剔除集合跟着变。
 * 于是 **B151**（magic 阴影"72 > 上限 50"）从头到尾是减法在骗人 —— 钉上世界种子后同配方五轮
 * 全读 39，只有那一次读到 72（整帧 584 / **本体 512**，比同日另一轮的 550 少 38 件：少的是本体趟）。
 * 2026-10-29 八站普查里幽暗站也一样：数出来 66、减出来 70。
 *
 * 修法不是给减法加容差（容差会变成下一次红之后被放宽的那个数），而是**另数一遍**
 * （`src/engine/shadowCensus.js` 复刻 three 的阴影趟规则）+ **再减一遍**（脚本里的"冻结对"：
 * 中间一次 `update()` 都不推的两趟）。两条在这里对上：
 * - `预测 !== 冻结阴影` ⇒ **模型或渲染在骗人**，这一站的阴影列不可解释 ⇒ 读数作废；
 * - `普查.问题` 非空 ⇒ 尺子自己没量到（VSM / 点光六面 / 读不到阴影相机 / 阴影趟没发）⇒ 作废。
 *
 * `报告阴影`（老口径那三列）与 `预测` 不等**不在这里红**：它是这一列的抖动，不是坏读数，
 * 脚本把它打印出来并登记进账本（B152）。把它当红，等于把"世界在动"记到代码头上。
 */
export function 普查读数问题(站id, 普查, 冻结阴影) {
  const 问 = [];
  if (!普查 || typeof 普查 !== 'object') {
    return [`站点 ${站id} 没交出阴影普查（拿到 ${JSON.stringify(普查)}）—— 阴影列这一轮没有独立的第二把尺`];
  }
  for (const 条 of (普查.问题 || [])) 问.push(`站点 ${站id} 的阴影普查尺子没量到：${条}`);
  if (问.length) return 问;
  if (!Number.isInteger(普查.预测)) {
    问.push(`站点 ${站id} 的普查预测不是整数（读到 ${String(普查.预测)}）—— 数出来的笔数只能是整数`);
  }
  if (!Number.isInteger(冻结阴影)) {
    问.push(`站点 ${站id} 的"冻结对"减法不是整数（读到 ${String(冻结阴影)}）—— 中间不 update 的两趟连数都没交出来`);
  }
  if (Number.isInteger(普查.预测) && Number.isInteger(冻结阴影) && 普查.预测 !== 冻结阴影) {
    问.push(`站点 ${站id} 的阴影趟对不上：模型数出来 ${普查.预测} 笔，同一份世界状态下减出来 ${冻结阴影} 个 call —— `
      + '两者必须在同一帧上相等（中间没有 update()）。不相等说明阴影趟里有一条规则没被复刻（或者 render 自己在改世界），'
      + '这一站的阴影列此刻**不可解释**，读数作废');
  }
  if (Number.isInteger(普查.预测) && 普查.预测 > 0 && !(普查.榜 || []).length) {
    问.push(`站点 ${站id} 数出来 ${普查.预测} 笔阴影却没有一行归属 —— 榜被丢了（归属与计数分家 = 下一轮没人知道这些 call 是谁）`);
  }
  return 问;
}

/**
 * CPU 腿：一站的推帧计时得交出什么。
 *
 * `应有帧数` 由脚本里的批数 × 每批帧推出来（不是这里写死的数）。帧数不够 = 有一批没回来，
 * 而那一批的缺席只会让 `均值` 变小或变 NaN，预算表的 `>` 永远抓不到它。
 */
export function cpu读数问题(名字, r, 应有帧数) {
  const 问 = [];
  if (!r || typeof r !== 'object') {
    return [`站点 ${名字} 没交出 CPU 腿读数对象（拿到 ${JSON.stringify(r)}）`];
  }
  if (r.frames !== 应有帧数) {
    问.push(`站点 ${名字} 交出 ${String(r.frames)} 帧，应有 ${应有帧数} 帧 —— 有一批计时没回来，均值是在缺样的样本上算的`);
  }
  for (const 列 of CPU列) {
    if (!是有限正数(r[列])) {
      问.push(`站点 ${名字} 的 "${列}" 读到 ${String(r[列])} —— 非有限正数过不了预算表的">"（NaN > 40 是 false），那一格会绿在空尺上`);
    }
  }
  return 问;
}

/**
 * 每帧调用点普查的腿（W-C2 切片19，#15 那把尺的**真读数**侧）。
 *
 * 这一条不管预算 —— 它管的是"这张榜是不是一次测量"。榜上第一格要是来自一把坏尺，
 * 后面所有的优化都会朝错的方向使劲，而错的方向看起来只是"跑得慢"。
 *
 * 形状（页面那一侧交出来的对象）：
 * `帧数` / `泵帧数` / `总耗时ms` / `已点名ms` / `其余ms` / `帧外ms` / `行[]` / `坏站点[]` /
 * `零调用[]` / `未接到[]` / `够不着[]` / `站点总数` / `装好数` / `被人改过[]` / `还原数`。
 *
 * "已点名不许大于整帧"这一条是**第一次真跑教出来的**（`.tmp-20261030-s22/census-r1.log`：hub 站
 * 已点名 1981.70 > 整帧 1956.10）：页自己的 rAF 与事件回调在两次 `evalJs` 之间也调了那些子系统，
 * 时间进了合计却没进整帧账。尺子现在把整帧账交给 `update` 自己记，并把帧外那一档分出去 ——
 * 于是这条不等式成了**构造上成立**的事，而它红的时候就是构造被改坏了的时候（臂会验这一点）。
 *
 * 归属率有下界（`普查归属下界`），出处是**第一份真读数**：2026-10-30 的 `perf:census` 八站读到
 * 98.6%—99.2%（`.tmp-20261030-s22/census-r2.log`，每站 72 个站点全接上、其余 0.1ms/帧）。
 * 下界取 0.5 不是"松一档好过"，是它要守的那件事的形状：榜一旦解释不了**过半**的帧，
 * 第一格就不再是热点，而是一张遮住了大半张账的收据。
 */
export const 普查归属下界 = 0.5;

export function 帧普查读数问题(站id, 出, 应有帧数) {
  const 问 = [];
  if (!出 || typeof 出 !== 'object') {
    return [`站点 ${站id} 没交出普查读数对象（拿到 ${JSON.stringify(出)}）`];
  }
  if (出.泵帧数 !== 应有帧数) {
    问.push(`站点 ${站id} 普查泵了 ${String(出.泵帧数)} 帧，应有 ${应有帧数} 帧 —— 有一批没回来，榜上的合计是在缺样的样本上加的`);
  }
  // 整帧账由 update 那层包装自己报，所以"页自己跑的帧"只会让 帧数 多于 泵帧数；反过来就是账丢了
  if ( typeof 出.帧数 === 'number' && typeof 出.泵帧数 === 'number' && 出.帧数 < 出.泵帧数) {
    问.push(`站点 ${站id} 见到 ${出.帧数} 帧却泵了 ${出.泵帧数} 帧 —— 泵出去的帧没进整帧账，"其余"就是凭空多出来的`);
  }
  if (出.坏站点.length) {
    问.push(`站点 ${站id} 有 ${出.坏站点.length} 处站点接不上对象：${出.坏站点.join(' / ')} —— 站点是从 update() 的函数体扫出来的，接不上就是尺子坏了，不许读成"这一格 0 毫秒"`);
  }
  if (出.装好数 === 0) {
    问.push(`站点 ${站id} 一处普查都没装上（名册 ${出.站点总数} 格全没接上）—— 这张榜是空的，而"空的"读起来像"都很便宜"`);
    return 问;
  }
  for (const 列 of ['总耗时ms', '已点名ms', '其余ms', '帧外ms']) {
    if (typeof 出[列] !== 'number' || !Number.isFinite(出[列])) {
      问.push(`站点 ${站id} 的 "${列}" 读到 ${String(出[列])} —— 非有限数，这张榜不能加减`);
    }
  }
  if (!问.length) {
    if (出.总耗时ms <= 0) {
      问.push(`站点 ${站id} 整帧合计 ${出.总耗时ms}ms —— 一帧都没真跑，榜上的数没有出处`);
    }
    // 榜不能吃超过整帧的账：超出了就是双计（嵌套的那条口径被改坏了）
    if (出.已点名ms > 出.总耗时ms + 1e-6) {
      问.push(`站点 ${站id} 已点名 ${出.已点名ms.toFixed(2)}ms > 整帧 ${出.总耗时ms.toFixed(2)}ms —— 合计里双计了（父的区间本来就含子）`);
    }
    // 余数必须是减出来的那一个数，不是另算的
    if (Math.abs(出.其余ms - (出.总耗时ms - 出.已点名ms)) > 1e-6) {
      问.push(`站点 ${站id} 的"其余"是 ${出.其余ms}，但 总 − 已点名 = ${出.总耗时ms - 出.已点名ms} —— 余数与账对不上`);
    }
    const 归属率 = 出.已点名ms / 出.总耗时ms;
    if (归属率 < 普查归属下界) {
      问.push(`站点 ${站id} 的榜只解释了整帧的 ${(归属率 * 100).toFixed(1)}%（下界 ${普查归属下界 * 100}%）`
        + ' —— 过半的账没人认领时，"榜上第一格"不再是热点，只是一张收据');
    }
  }
  if (!出.行.length) {
    问.push(`站点 ${站id} 的榜是空的（装了 ${出.装好数} 处却一行没有）`);
  } else {
    const 乱序 = 出.行.filter((一, k) => k > 0 && 一.合计ms > 出.行[k - 1].合计ms);
    if (乱序.length) {
      问.push(`站点 ${站id} 的榜没按合计降序：第一格 ${出.行[0].名} ${出.行[0].合计ms}ms，乱序 ${乱序.length} 格 —— "榜上第一格"就指错了地方`);
    }
    const 无名 = 出.行.filter((一) => !一.名);
    if (无名.length) 问.push(`站点 ${站id} 有 ${无名.length} 行没有名字 —— 指认不出是哪个调用点`);
  }
  if (出.被人改过.length) {
    问.push(`站点 ${站id} 卸普查时发现这些方法已不在位：${出.被人改过.join(' / ')} —— 这一轮的榜是两个人合著的，谁的补丁在位说不清`);
  }
  if (出.还原数 !== 出.装好数) {
    问.push(`站点 ${站id} 装了 ${出.装好数} 处却还原 ${出.还原数} 处 —— 补丁没还清，后面的腿读的是被改过的游戏`);
  }
  return 问;
}

/**
 * 名册覆盖：交出来的站点集合必须与名单**逐格**相等。
 *
 * 少一站 = 那一站被静默跳过（与"上限表缺站"同罪，但那条查的是表，这一条查的是**这一轮真跑了**）；
 * 多一站 = 脚本自己发明了一站，名册不再是唯一答案；顺序也钉 —— 日志与读数得与上限一一对得上，
 * 否则"逐站上限"会被贴到别人的读数上。
 */
export function 覆盖问题(名单, 读数) {
  const 交 = 读数.map((r) => r?.站);
  const 问 = [];
  const 少 = [...名单].filter((id) => !交.includes(id));
  const 多 = 交.filter((id) => !名单.includes(id));
  const 重 = 交.filter((id, i) => id !== undefined && 交.indexOf(id) !== i);
  if (少.length) 问.push(`名册里有这一站却没交出读数：${少.join(', ')} —— 那一站被静默跳过（= 静默放开）`);
  if (多.length) 问.push(`交出了名册外的站点读数：${多.join(', ')} —— 站点名单的唯一真源是名册`);
  if (重.length) 问.push(`同一站交出多份读数：${[...new Set(重)].join(', ')} —— 逐站上限会被贴到错的那一份上`);
  if (!问.length && 交.join(',') !== [...名单].join(',')) {
    问.push(`站点顺序与名册不一致：交出 ${交.join(',')} / 名册 ${[...名单].join(',')} —— 逐站上限是按站贴的，顺序漂了就贴错地方`);
  }
  return 问;
}

/**
 * CDP 口的形状：Chrome 自己报出来的那一行里必须有的东西。
 *
 * 判定放在这里（而不是只写在脚本里）是为了让门禁能**喂真字符串**验它：
 * 一条从不被坏输入走过的解析，等于一条没测过的解析。
 */
export const DEVTOOLS行 = /DevTools listening on ws:\/\/127\.0\.0\.1:(\d+)\/devtools\/browser\/(\S+)/;

/** 从 Chrome 的 stderr/stdout 全文里取口；取不到就返回 null（由调用方决定怎么红） */
export function 解析CDP口(全文) {
  const 匹 = DEVTOOLS行.exec(String(全文 ?? ''));
  if (!匹) return null;
  const 口 = Number(匹[1]);
  if (!Number.isInteger(口) || !(口 > 0) || 口 > 65535) return null;
  return { 口, 浏览器ws: `ws://127.0.0.1:${口}/devtools/browser/${匹[2]}` };
}

/**
 * 页归属：`/json/list` 里挑的是**第一个** `type === 'page'`，同一台浏览器里可能有别人开的页。
 *
 * 前缀带尾斜杠不是排版洁癖：端口是数字，`http://127.0.0.1:5199` 能匹配上 `51990` 那台服务的页
 * —— 数字前缀没有边界，尾斜杠就是那道边界。
 */
export function 页地址问题(页地址, 端口) {
  const 文 = String(页地址 ?? '');
  const 期望 = `http://127.0.0.1:${端口}/`;
  if (文.startsWith(期望)) return [];
  return [`连到的页不是本进程的页：location.href=${文.slice(0, 160) || '(空)'}（应以 ${期望} 开头）`];
}

/**
 * 通道自证：`exceptions.length === 0` 有两种成因 —— 页面真没抛，与事件通道一条都没送。
 * 前者是达标，后者是空尺，读出来是同一个 0。
 *
 * `Runtime.enable` 一定 flush 现存执行上下文，所以"执行上下文 ≥ 1"是一个**正面**见证
 * （数的是必然会来的东西），不是又一个"没看到坏东西"。
 */
export function 通道问题(通道) {
  const 条 = 通道?.执行上下文;
  if (Number.isInteger(条) && 条 > 0) return [];
  return [`CDP 事件通道一条事件都没送（执行上下文 ${String(条)} 条）—— 后面那句 exceptions=0 不作数：通道断了与页面没抛错读出来是同一个 0`];
}

/**
 * 中途全量重载 = 这一轮的读数**不作数**（W-C2 切片6d，#167）。
 *
 * 症状见过两次（2026-10-22）：另一路会话在跑批期间往 `src/` 里写了一下 ⇒ vite 发 full reload ⇒
 * 页面里的 `window.__game` 变回 undefined ⇒ 下一句 `evalJs` 红成
 * `TypeError: Cannot read properties of undefined (reading 'player')`。
 * **红得像是代码坏了**，而实际是这一轮的量被换掉了 —— 归因错一次的代价是把别人的提交回滚了
 * 或者把自己的好改动"修"一遍。
 *
 * 判据用一个已经在数的数：执行上下文的条数。一页活到底，它不会自己再涨（本仓没有 worker，
 * 也没有 iframe）；**动了就说明页被重建过**（重建会先把旧上下文销毁，所以条数也可能变小 ——
 * 只防"变多"是半个判据）。所以这里要的是"测量开始前的条数"与"现在的条数"相等。
 *
 * `基线 === null` 是**还没取到基线**（这一轮在见证之前就死了），不作判、也不假装判过 ——
 * 其他任何非整数都算这条作废判据自己没喂到数，点名拒绝。
 */
export function 重载问题(基线, 结束) {
  if (基线 === null) return [];
  if (!Number.isInteger(基线)) {
    return [`基线条数不是整数（读到 ${String(基线)}）—— 这条作废判据自己被喂了个空尺`];
  }
  const 差 = 结束 - 基线;
  if (差 === 0) return [];
  return [`测量期间页面的执行上下文从 ${基线} 条变成 ${结束} 条（差 ${差}）—— 页在中途被重建过（全量重载）。`
    + '成因有两种、处置完全不同：别人在这轮跑的时候往 `src/` 写了一下，与 vite 自己在冷启动之后发的那一次 reload'
    + ' —— 前者重来一轮就好，后者每一轮都红在同一格（带 `重载线索` 交出来的那几行 vite 原话点名是哪一种）。'
    + '这轮的每一个读数都不是从同一个页里读出来的，**这一轮不作数**'];
}

/**
 * **为什么**这个页被换掉：从 vite 自己的话里取出它能说的那几行（W-D4 切片7）。
 *
 * `重载问题` 说"页被重建过"，但它的两个输入就是条数 —— 说不出成因。而下一件事完全取决于成因：
 * - **别人在跑批期间往 `src/` 写了一下**（共用工作树的常态）：不是这一轮的错，等他们停下来重来一轮；
 * - **vite 自己在冷启动之后发了那一次 reload**（预打包完依赖 / 扫到新入口）：那是**启动噪声**，
 *   说明基线取早了 —— 这种红每一轮都在同一格，重来一万次也不会绿。
 *
 * 2026-10-31 真撞上第二种：`e2e-combat` 连着两轮都在**同一个位置**（通道见证之后、第一站之前）被重建，
 * 而那两百多秒里 `src/` 根本没写过（按 mtime 对过账：最近一次写在我这轮开始之前四分钟）。
 * 把这种红写成"最常见的原因：有人往 src/ 写了一下"，下一个人会去查一个没被改过的提交 ——
 * 所以这里把 vite 打出来的那几行原样交给调用方：`page reload src/core/Game.js` 点得出文件，
 * `✨ new dependencies optimized: three` 点得出是冷启动。**一行话的归因**与"猜一个常见原因"
 * 的差距就是这一条。
 *
 * **锚点是照它自己的 format() 抄的，不是照印象**（同一个红法第二次撞上时才对出来）：
 * vite 的 logger 打的是一行 `${dim(HH:MM:SS)} ${cyan([vite])} ${msg}` —— 时间戳在 `[vite]` **之前**
 * （见 `node_modules/vite/dist/node/chunks/*.js` 里 `createLogger` 的 `format()`）。
 * 只认行首 `[vite]` 的话，真轮次里**一行都收不到**，于是红话说的是"vite 一句都没说"，
 * 而真相是我们的过滤器不对 —— 这句假清白比没有成因更坏：它把"过滤器写错了"报成了"没人动过手"。
 * 所以这里的时间戳段是可选的（`00:59:12` / `12:34:56 AM` / `00.59.12` 都认），
 * 而正文里恰好引用了 `[vite]` 的那一句（前面跟着别的话）仍然不算成因。
 *
 * 取**尾部**：一条跑几分钟的轮次里 vite 能刷上百行，红的时候要看最后那几次动作，不是开机横幅
 * （横幅那些不带 `[vite]` 前缀的行天然被滤掉 —— 只收它真的在说话的那行）。
 * ANSI 色带先剥：带着色标的行既读不出文件名的边界，也没法在门禁里喂真字符串比对。
 */
export const 重载线索上限 = 6;

/** `HH:MM:SS` / `HH.MM.SS` / `12:34:56 AM`（后两位是 `Intl` 按 locale 加的）—— vite 打在 `[vite]` 前面那一段 */
const 时间戳 = '(?:\\d{1,2}[.:]\\d{2}(?:[.:]\\d{2})?(?:\\s*[AP]M)?\\s+)?';
const 是vite的话 = new RegExp(`^${时间戳}\\[vite\\]`);

export function 重载线索(全文) {
  const 剥色 = String(全文 ?? '').replace(/\u001b\[[0-9;]*m/g, '');
  return 剥色.split(/\r?\n/)
    .map((行) => 行.trim())
    .filter((行) => 是vite的话.test(行))
    .slice(-重载线索上限);
}

/**
 * 判据**交白卷时**用的那几行：原样的尾部输出，不认前缀。
 *
 * `重载线索` 收不到东西的时候，调用方手里只剩两种可能，而它自己分不开：
 * ① dev server 这一轮真的没说（那次重载不是它发的 —— 是浏览器自己导航、或页里的脚本 reload）；
 * ② 我们的过滤器不对（上面那段就是被这一条逮到的）。
 * 把 ② 写成 ① 的那句清白话，代价是把下一轮的真因又埋一次 —— 所以这里把原话尾巴交出去，
 * "没收到"这句话只有在尾巴也是空的时候才允许说出口。
 */
export function 原话尾巴(全文, 条数 = 3) {
  const 剥色 = String(全文 ?? '').replace(/\u001b\[[0-9;]*m/g, '');
  return 剥色.split(/\r?\n/).map((行) => 行.trim()).filter(Boolean).slice(-条数);
}

/**
 * 战斗门禁的**越线表**（W-D4 切片7c）：把 `e2e-combat` 那五条"这轮算不算过"从脚本里搬出来。
 *
 * ## 为什么搬（不是因为想复用，是因为前两条写错了而写错了没法被演示）
 *
 * 2026-11-02 这一条门禁第一次跑完整轮（r7），红了两条，两条都是判据自己踩空：
 * - **站 1 拿首末两点当轨迹**：夹具把玩家扔到兵跟前时，那只兵已经在 `windup` 里，
 *   120 帧（2 秒模拟）打完一套连段又回到 `windup` —— `后 === 前`，报的是"没有追击/出手"，
 *   而同一个读数里 `我掉血` 是 `true`。判据把"正在打"读成了"卡住"。
 * - **站 2 在断气那一帧读魂火账**：击杀的魂魄是 `loot.spawnKill()` 掉在地上的一件掉落物，
 *   要玩家走进拾取半径才 `addSouls`；`while (兵.alive)` 一退出就读账，读到的 0 是"还没踩上去"。
 *
 * 这两条在脚本里是改不了的：脚本要么真起浏览器，要么什么都不测。搬成纯函数之后
 * `tests/e2e-combat.test.js` 能拿**合成读数**把两个形状各跑一遍 —— 卡在单一态的轨迹必须红、
 * 走完 windup→strike→recover 的轨迹必须绿、断气时掉距 6 米且窗尽头仍是 0 必须红。
 *
 * ## 切片7d 补的第三格：入账 ≠ 这一只兵的账
 *
 * r8 绿了，可 `掉落在场 = 15` 暴露了收尸那一站的取值法：它朝**最近的一份**走，而竞技场里
 * 躺着十几份别人的旧掉落。于是 `魂入账 = +25` 严格说的是"这片地上有一份被踩到了"，
 * 不是"这一只兵掉的那一份被踩到了" —— 恰好是这条门禁本该证明的那件事。现在页那边按
 * 对象身份 diff（断气前不在册）+ 断气点半米内 + `!gear && souls > 0` 认出那一枚，
 * 判据多吃两个读数：认不出来红；入账了但那一枚还躺在场上也红（钱不是它带来的）。
 *
 * ## 失败闭合
 *
 * 每一格都按"读不出来就是越线"写：`轨迹` 不是数组就红（采样那行被删了不该表现为"没卡死"），
 * `魂入账` 用 `> 0` 而不是 `!== 0`（`undefined`、`NaN`、负数都不算入账），`杀掉` 只认真值。
 * 这条门禁的红话必须比数字多说一点（认领距、用了多少帧），否则下一次红还是同一轮考古。
 *
 * @param {{ai: {轨迹?: unknown, 我掉血?: boolean, 复活?: number, 顶次数?: number}, 击杀: {杀掉?: boolean, 魂入账?: number, 认领距?: number|null, 认领souls?: number, 新掉落数?: number, 魂火离场?: boolean, 收尸帧?: number, 击杀账?: Record<string, number>, 复活?: number, 顶次数?: number, 起手?: number, 判定?: number, 有人挨刀?: number, 兵掉血?: number, 击倒?: number, 偏差?: number, 刃长?: number|null, 三米内?: number, 补锁?: number, 按下?: number, 可起帧?: number, 冻帧?: number, 冻因?: Record<string, number>, 关弹窗?: number}}} R 三站读数
 * @param {{aiProbeFrames: number, aiEngagedStates: string[], lootProbeFrames: number, maxKillFrames: number, playerHp: number, minKillLedger: number, exceptions: number}} 预算
 * @param {string[]} [异常] 页面里未捕获的异常文本
 * @returns {string[]} 越线的话，空数组 = 这一轮过
 */
export function 战斗越线(R, 预算, 异常 = []) {
  const out = [];
  /**
   * —— 切片11：三站认的是不是**同一枚兵** ——
   *
   * 旧形状里站 0 把玩家搬到"第一只活着的兵"旁边，站 1 与站 2 再各自数一遍同一个表达式。
   * 中间只要那只兵被摘出 `enemies`（`EnemyManager` 的 despawn 与死亡两条路都 splice），
   * 后两站的 `find` 就安静地递上**另一只** —— 而日志里"轨迹只有 idle"与"看的不是同一只"
   * 长得一模一样。这一格把等号变成读数：标记是对象身份，丢了就点名，不再靠事后探针考古。
   */
  const 站1丢 = R?.ai?.标记丢了 === true;
  const 站2丢 = R?.击杀?.标记丢了 === true;
  if (站1丢 || 站2丢) {
    out.push(`三站认的不是同一枚兵：站 1 ${站1丢 ? '认不出' : '认得出'}、站 2 ${站2丢 ? '认不出' : '认得出'}站 0 那枚标记`
      + ' ⇒ 名单在两次 CDP 请求之间被换过，这一轮的"轨迹"与"打不死"都不是那枚兵的读数');
  }
  /**
   * —— 切片11 尾巴：厚血夹具**这一窗里有没有一直保住玩家** ——
   *
   * r11 / r12 那两轮的红（1600 帧打不死、认不出自己那枚魂火、击杀账本空）不是三个 bug，是**一个**：
   * 夹具那句 `hp = 99999` 被游戏自己的结算重算顶回基础值（探针读到 99957 → 118，同一格里 我魂 从 0 变 15），
   * 玩家当场变成凡人，被围死之后走 `CombatController.respawn()` ⇒ `player.teleport(0, 2, 55)` ——
   * 于是 `死距 225.89` 而 `兵离家 4.5`：走掉的是玩家。现在脚本每帧把夹具续回来，并把游戏自己派的
   * `player-respawn` 数交回来。**这一条红是"续不住"的哨兵**：复活过 > 0 就说明这一站后半程两侧量的
   * 不是同一场战斗，此时下面每一格都只该当噪音读。
   */
  const 复活 = (Number(R?.ai?.复活) || 0) + (Number(R?.击杀?.复活) || 0);
  if (复活 > 0) {
    out.push(`厚血夹具没保住玩家：站 1 复活 ${Number(R?.ai?.复活) || 0} 次、站 2 复活 ${Number(R?.击杀?.复活) || 0} 次`
      + `（每帧顶回 ${JSON.stringify(R?.ai?.顶次数)}/${JSON.stringify(R?.击杀?.顶次数)} 次）`
      + ' ⇒ 死过一次就走 respawn() 的 teleport，此后"轨迹""打不死""没入账"量的都不是那枚兵'
      + `｜站 2 末 玩家 ${JSON.stringify(R?.击杀?.玩家坐标)} 兵 ${JSON.stringify(R?.击杀?.兵坐标)}`);
  }
  /**
   * 这一窗里世界**有没有在推进**：`sense.dist` 是 `EnemyManager.update → Enemy.update → Sense.update`
   * 那条链的必经产物，它一路读不出数就说明这一页根本没跑到这只兵（暂停/界面层挡在 `playing` 那一格，
   * 或这一格被剔除）。此时下面每一条读数都只是"没动"，不是"没问题"，也不是"AI 坏了"。
   */
  if (R?.ai?.没推进 === true) {
    out.push(`站 1 的 ${预算.aiProbeFrames} 帧里那枚兵的 sense.dist 始终读不出数`
      + ' ⇒ 世界没在推进（暂停/界面层挡住，或这一格被剔除）—— 此时"轨迹"与"掉血"都不算证据');
  }
  const 轨迹 = R?.ai?.轨迹;
  if (!Array.isArray(轨迹) || 轨迹.length === 0) {
    out.push(`AI 通路：这一轮没交出状态轨迹（读到 ${JSON.stringify(轨迹)}）—— 采样那一行断了，此时"没卡死"这句话没有依据`);
  } else {
    const 出手过 = 轨迹.filter((s) => 预算.aiEngagedStates.includes(s));
    if (出手过.length === 0) {
      // 带得上"人还在不在它旁边"：同样是全程 idle，2.2 米是 AI 回归，几十米是夹具/几何
      out.push(`AI 通路：${预算.aiProbeFrames} 帧里只走过 ${轨迹.join('→')}，没进 ${预算.aiEngagedStates.join('/')} 任何一档`
        + `｜首帧距 ${JSON.stringify(R?.ai?.首帧距)} 米｜末帧距 ${JSON.stringify(R?.ai?.末帧距)} 米`);
    }
  }
  if (!R?.ai?.我掉血) {
    // 同样带距离：轨迹里有 windup/strike 却一点血没掉，2.4 米是"打空了"（AI/命中那一侧的事），
    // 几十米是"人早就不在场"（夹具那一侧的事）—— 旧红话只有前半句，两件事只能靠探针分。
    // 证人换成游戏自己派的事件计数（切片11 尾巴）：旧那句"血量仍等于基线"量的其实是
    // "两次 CDP 请求之间那半秒"，而且夹具每帧顶回之后它永远为真 —— 那是一条会说谎的红。
    out.push(`AI 通路：${预算.aiProbeFrames} 帧里一次 player-damaged 都没有 ⇒ 那兵根本没打到我`
      + `（状态名对上也不算出手）｜首帧距 ${JSON.stringify(R?.ai?.首帧距)} 米｜末帧距 ${JSON.stringify(R?.ai?.末帧距)} 米`);
  }
  /**
   * —— 切片11b：打不死要说得出**断在哪一环**（兑现 → 出招 → 判定 → 挨刀 → 那一枚掉血 → 击倒）——
   *
   * r13 夹具续住了（我hp 99999、复活 0、死距 2.58、兵离家 4.6），红话却只有一句"1600 帧没打死一只兵"。
   * 那一轮的探针（wb7-13-hitprobe.log）读的是**出招全通、一刀没落**：我态一路 light/combo，
   * 两枚 combat-hit 证人 1680 帧全是 0，而那枚兵就在 2.2 米、最近、身边三米内只有它 ——
   * 玩家侧对着它挥刀（轻击锥 acos(0.12)≈83°，垂直那一个正好溜在锥沿外）。
   * 这一族红把那一句话拆成四档，并且只报**第一处断的**那一环：环是链，全报会把"没出招"和
   * "砍错人"混成同一片噪音。四格读数**缺任何一格就不演这一出**（与 复活 / 我hp 同一套分工：
   * 数有没有交回来归产侧腿 打中证人在 钉，这里只管"数说的事"，一条会说谎的红比没有红更坏）。
   *
   * r14 把这根链再往上游接了一档，因为那一轮四档**没有一档断在 0**（偏差 0°、挨刀 3、那一枚掉血 88、
   * 死距 2.67）却依然"1600 帧没打死"：探针 wb7-14-whyprobe.log 读到的真相是**体力全程够
   * （够力帧 200/200）而 combat.canStart('light') 从第 110 帧起恒假**，因为连段处决派了
   * combo-finisher ⇒ ContextualTutorial 弹出一枚**模态**教学，而 Game.js:1041-1056 的 playing 一关
   * 把 player.update（含 combat.update）整条冻住 1400 帧。那句话的主语从此不是"刀"，是"手"：
   * **兑现**那一档问的是"游戏有没有允许这一招打出来"，排在出招之前。判据用 可起帧 === 0
   * 这个**性质**（一帧都没允许过），不立"按下/起招 至少要几比几"的比值 —— 比值是抄进来的常数，
   * 而这一格是游戏自己那张 cancel 表的答案。
   */
  if (R?.击杀?.杀掉 !== true
    && ['起手', '判定', '有人挨刀', '兵掉血'].every((k) => typeof R?.击杀?.[k] === 'number')) {
    const 数 = (k) => R?.击杀?.[k];
    const 尾 = () => `｜起手 ${JSON.stringify(数('起手'))} 招｜判定 ${JSON.stringify(数('判定'))} 次`
      + `｜有人挨刀 ${JSON.stringify(数('有人挨刀'))} 下｜那一枚掉血 ${JSON.stringify(数('兵掉血'))}`
      + `｜偏差 ${JSON.stringify(R?.击杀?.偏差)}°｜刃长 ${JSON.stringify(R?.击杀?.刃长)}`
      + `｜三米内 ${JSON.stringify(R?.击杀?.三米内)} 只｜补锁 ${JSON.stringify(R?.击杀?.补锁)} 次`
      + `｜玩家停在 ${JSON.stringify(R?.击杀?.我招)} 那一档`;
    const 起手 = 数('起手'); const 判定 = 数('判定');
    const 挨刀 = 数('有人挨刀'); const 掉血 = 数('兵掉血');
    if (数('可起帧') === 0) {
      out.push(`${预算.maxKillFrames} 帧里 combat.canStart('light') 一次都没开过`
        + `（按下 ${JSON.stringify(数('按下'))} 次、只登记了 ${起手} 招）`
        + ` ⇒ 断在**兑现**：游戏根本没允许出招，体力与命中几何都轮不到说话`
        + `｜输入被冻 ${JSON.stringify(数('冻帧'))} 帧 ${JSON.stringify(R?.击杀?.冻因)}`
        + `｜驱动代点掉弹窗 ${JSON.stringify(数('关弹窗'))} 次${尾()}`);
    } else if (起手 === 0) {
      out.push(`${预算.maxKillFrames} 帧里 combat 一次都没登记新招（_setStrike 的边沿为 0）`
        + ` ⇒ 断在**出招**：左键边沿没进缓冲、体力不够或被取消窗口挡住，与命中几何无关${尾()}`);
    } else if (判定 === 0) {
      out.push(`登记了 ${起手} 招而命中窗口一次都没结算（attackHitDone 从没翻成真）`
        + ` ⇒ 断在**判定**：每一招都在 move.at 之前被打断（翻滚/受击/时间缩放），与兵在哪无关${尾()}`);
    } else if (挨刀 === 0) {
      out.push(`${判定} 刀全部落空：没有任何一只兵挨到一下（带 detail 的 combat-hit 为 0）`
        + ` ⇒ 断在**打中**：锥/刃长/竖直带里都没有它，玩家根本没朝它挥${尾()}`);
    } else if (掉血 <= 0) {
      out.push(`砍到的是别的兵：场上有人挨刀 ${挨刀} 下、倒下 ${JSON.stringify(数('击倒')) ?? '—'} 只，`
        + `而标记那一枚一滴血没掉 ⇒ 断在**打的谁**：锁定/身份没落在那枚兵身上${尾()}`);
    }
  }
  if (!R?.击杀?.杀掉) {
    // r11 只有 死距 一个数，于是"1600 帧没打死"有三种完全不同的读法（兵归巢 / 玩家被推走 /
    // 厚血夹具被顶掉），而它们在这句话里长得一模一样。把两侧坐标与"从第几帧走出自己的仇恨圈"
    // 一起交出来，归因就不用再靠事后探针考古 —— 这一格是**读数**，不是新的判据。
    out.push(`${预算.maxKillFrames} 帧真输入没打死一只兵（敌血没走完）`
      + `｜兵血 ${JSON.stringify(R?.击杀?.兵血)}｜死距 ${JSON.stringify(R?.击杀?.死距)} 米`
      + `｜分开首帧 ${JSON.stringify(R?.击杀?.分开首帧)}（出 仇恨圈 ${JSON.stringify(R?.击杀?.仇恨圈)} 米）`
      + `｜兵离家 ${JSON.stringify(R?.击杀?.兵离家)} 米｜我hp ${JSON.stringify(R?.击杀?.我hp)}`
      + `｜玩家 ${JSON.stringify(R?.击杀?.玩家坐标)} 兵 ${JSON.stringify(R?.击杀?.兵坐标)}`);
  }
  // 「这一只兵自己的那枚魂火」认不出来 ⇒ 后面那句"入账了"证明不了任何东西（切片7d）
  const 认领souls = R?.击杀?.认领souls;
  if (!(typeof 认领souls === 'number' && 认领souls > 0)) {
    out.push(`击杀后认不出这一只兵自己的那枚魂火：断气后新增 ${JSON.stringify(R?.击杀?.新掉落数)} 份掉落，`
      + `里面没有"落在断气点半米内、且 !gear 而 souls>0"的那一枚（souls 读到 ${JSON.stringify(认领souls)}）`);
  }
  const 入账 = R?.击杀?.魂入账;
  if (!(typeof 入账 === 'number' && 入账 > 0)) {
    out.push(`击杀后 ${预算.lootProbeFrames} 帧内没踩到那一枚魂火：魂火 +${JSON.stringify(入账)}`
      + `｜认领距 ${JSON.stringify(R?.击杀?.认领距)} 米｜收尸用了 ${JSON.stringify(R?.击杀?.收尸帧)}/${预算.lootProbeFrames} 帧`);
  } else if (!R?.击杀?.魂火离场) {
    out.push(`魂火 +${入账} 了，但认出来的那一枚（${JSON.stringify(认领souls)} 魂）还躺在场上`
      + ` ⇒ 这笔账是别的东西入的，这一轮没证明"击杀→掉落→拾取"那条链`);
  }
  const 击杀数 = Object.values(R?.击杀?.击杀账 ?? {}).reduce((s, n) => s + (Number(n) || 0), 0);
  if (击杀数 < 预算.minKillLedger) out.push(`击杀账本是空的：quest stats.kills 没记 ${JSON.stringify(R?.击杀?.击杀账 ?? {})}`);
  if (异常.length > 预算.exceptions) out.push(`页面异常 ${异常.length} 条 > ${预算.exceptions}：${异常[0] ?? ''}`);
  return out;
}

