/**
 * 无头 E2E 门禁的**预算表**（`npm run e2e` 与 `npm run e2e:combat` 共用这一个模块）
 * —— 与脚本分家的原因见下。
 *
 * ## 为什么单独一个文件（而不是写在 `e2e-clear.mjs` / `e2e-combat.mjs` 里）
 *
 * 那两个脚本都是**导入即执行**的：它们顶层就起 vite、起 Chrome、跑完整条链。
 * 门禁要的只是这几张表，可一旦 `import` 那些脚本，
 * 就会在 `npm test` 里真起一个浏览器把 E2E 跑一遍 —— 单测因此慢一个量级，
 * 还会因为脚本里的 `process.exit` 在 vitest 里报一条"未捕获异常"。
 *
 * 这不是假想的：`perf-smoke.mjs` 就是这个形状，全量套件里那条
 * `Error: process.exit unexpectedly called with "0"`（源自 `scripts/perf-smoke.mjs:216`）
 * 就是它 —— `tests/perf-smoke.test.js` 为了拿 `PERF_BUDGETS` 而 import 了脚本本体。
 * 那一处同时改成了 `scripts/perf-budgets.mjs`。**判据与执行分家**是这一族问题的通用解。
 *
 * ## 表本身
 *
 * `maxFrames` 的来历：实测一次通关 **5160 帧 = 86 秒模拟时间**（44 步 × 传送 + 步内 + 步间，
 * 加上每步 `syncProgress()` 级联推进的等待），连跑三次逐帧相同。取 **12000 帧（200 秒）**
 * ≈ 2.3 倍余量。它防的是"主线在某一步上永远走不完"（事件名改了、目标点没了、章节门配错）——
 * 那种情况下这个数会一直涨到预算耗尽，这正是要抓的形状。
 */

/**
 * 预算表（门禁 `tests/e2e-clear.test.js` 钉住这几个数不许被悄悄放松）。
 */
export const E2E_BUDGETS = {
  /** 推帧上限（模拟时间 = frames / 60 秒）：走不完就是走不完，不许无限等 */
  maxFrames: 12000,
  /** 未捕获异常：0 条。通关路上一次都不许抛 */
  exceptions: 0,
  /** 必须真的走到"通关"（`quests.completed === true`）—— 关掉它就等于把这条门禁废了 */
  requireCompleted: true,
  /** 主线步数下限（分母守卫）：步数少到这个数以下，说明任务表被掏空了，"通关"是空转 */
  minMainlineSteps: 30,
};

/**
 * 战斗 E2E 冒烟的阈值（门禁 `tests/e2e-combat.test.js` 钉住这几个数不许被悄悄放松）。
 *
 * 这几样各守一件事：
 * - `aiProbeFrames` + `aiEngagedStates`：玩家贴脸后推这么多帧，兵的**轨迹**里必须出现追击或出手。
 *   "轨迹"是这一版的关键：r7 之前问的是"最后一帧的态和第一帧不同吗"，而那只兵起手就已经在
 *   `windup` 里，两秒打完一套连段又回到 `windup` —— 首末相等，看着像卡死，其实是**在打**。
 *   调大 `aiProbeFrames` = "AI 不出手"这条越线变成"AI 出手得慢一点"。
 * - `maxKillFrames`：真输入（每 12 帧一次左键边沿）打死一只兵最多允许这么多帧。
 *   它防的是"打击窗口与结算分家"那种断链 —— 把它从 2400 抬到 24000，
 *   门禁还在跑，但它已经改成"总有一天打得死"。
 *   **这一列的"帧"是模拟帧**：脚本把 `clock.getDelta` 钉成 1/60（切片7b，与 `e2e-clear` 同一条），
 *   所以 `帧数 / 60` 就是这一场战斗的模拟秒数，与这台机器当时忙不忙无关。
 * - `playerHp`：**夹具不是预算**，写进表里的理由是那个数在页面里出现三次
 *   （设值两次 + "我掉血 / 掉过血"两次都拿它当基线）。两处各写一份字面量时，
 *   改一处就会让"掉血"这个证人静默失效（要么恒真、要么恒假），所以它得是同一个真源。
 */
export const E2E_COMBAT_BUDGETS = {
  /** AI 通路的观察帧数（站 1 推帧数） */
  aiProbeFrames: 120,
  /**
   * 站 1 认可的"兵真的在打"那几档，**逐格必须是 `EnemyFSM` 里的态名**。
   *
   * 这一列第一次跑轮（2026-11-02 r7）抄的是 `['pursue','attack','light','heavy','strike']`
   * —— 后三个是 `CombatController` 的**玩家**态，敌人那一侧压根没有这三档，
   * 于是白名单里有两格是死字。现在由 `tests/e2e-combat.test.js` 拿
   * `ENEMY_STATE_NAMES` 逐格核对，抄错当场红。
   *
   * 为什么不含 `windup`：前摇是"已经起手还没落"，它单列出现正是要抓的形状
   * （承诺态走不完 = AI 卡在半空）；真出手的证据是 `strike` 与其后的 `recover`。
   * 为什么不含 `orbit`：绕外圈是**没抢到围攻名额**的等待态，说明感知通了但没打，
   * 拿它当证人会把"八只同时起手"那个老问题重新放过去。
   */
  aiEngagedStates: ['pursue', 'strike', 'recover'],
  /**
   * 击杀后再推这么多帧去**踩那一枚魂火**（站 2 的收尸窗口）。
   *
   * 为什么要这一窗：魂火不是击杀那一行直接进 `stats.souls` 的 ——
   * `EnemyManager` 在敌人断气那一帧调 `loot.spawnKill()` 把魂魄**掉在地上**
   * （`src/combat/EnemyManager.js:516`），要等玩家走进 `LootSystem` 的拾取半径
   * 才 `addSouls`（`src/game/LootSystem.js:388-390`）。r7 那句
   * "击杀后魂火没入账（+0）"就是这么来的：`while (兵.alive)` 一退出就立刻读账，
   * 读到的是"魂魄还躺在地上"的那个瞬间，不是结算链断了。
   *
   * 窗口的存在不等于放松 —— 窗尽头账仍是 0 就照红，而且红话里带着认领距。
   * 切片7d 起这一窗走的不是"最近的一份掉落"而是**这一只兵自己的那一枚**
   * （断气前不在册 + 落在断气点半米内 + `!gear && souls>0`）：竞技场里同时躺着
   * 十几份别人的旧掉落（r8 `掉落在场 = 15`），按最近挑等于把"击杀→拾取"这条链
   * 证成了"这片地上有东西被踩过"。上限按 `DROP_LIFE = 30` 秒（钉步长下 1800 帧）留足。
   */
  lootProbeFrames: 600,
  /** 真输入击杀的帧预算：耗尽还没打死就是越线 */
  maxKillFrames: 2400,
  /**
   * 每多少帧画一次（切片7b）。**默认写法是每帧都画，那一档这一条门禁跑不完**：
   * 无头 Chrome 用软件 GL，实测一帧 `render()` 约 2.1 秒（`.tmp-20261031-s24/probe-framecost.log`：
   * 空闲 纯update 171.6 ms/帧 vs update+render 2271.5 ms/帧），2400 帧就是四十多分钟
   * —— 2026-10-31 真跑一轮，通道见证之后 40 分钟没走到交账。
   *
   * 为什么不干脆取消：三站的断言全是逻辑的（AI 状态、敌血、魂火、账本），但"打着打着画面管线炸了"
   * 也只有 `render()` 会撞出来。按这个节拍画 = 一整场战斗里仍有若干次真绘制，代价从
   * 2400 次降到个位数。**把它调回 1 就是让这条门禁不可运行，不是让它更严**。
   */
  renderEvery: 240,
  /** 玩家厚血：冒烟不是平衡测试，但"被打死"要能被 `hp < playerHp` 问出来 */
  playerHp: 99999,
  /** 击杀账本下限（分母守卫）：魂火与账本各记一次才算"结算链"通 */
  minKillLedger: 1,
  /** 未捕获异常：0 条 */
  exceptions: 0,
};
